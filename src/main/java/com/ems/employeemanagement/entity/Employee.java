package com.ems.employeemanagement.entity;

import com.ems.employeemanagement.enums.EmploymentStatus;
import com.ems.employeemanagement.enums.Gender;
import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.SQLDelete;
import org.hibernate.annotations.UpdateTimestamp;
import org.hibernate.annotations.Where;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;

/**
 * Represents an employee's HR profile.
 *
 * <p>An Employee record is distinct from a User record:
 * <ul>
 *   <li>User = security principal (login credentials and roles)</li>
 *   <li>Employee = HR data (name, salary, department, etc.)</li>
 * </ul>
 *
 * <p><strong>Soft Delete:</strong>
 * Instead of physically deleting an employee record (which would cascade
 * and destroy historical attendance, leave, and payroll data), we set
 * {@code is_deleted = true}. Hibernate's {@code @SQLDelete} overrides
 * the DELETE SQL, and {@code @Where} filters out deleted records from
 * all queries automatically.
 */
@Entity
@Table(
    name = "employees",
    indexes = {
        @Index(name = "idx_emp_code",          columnList = "employee_code", unique = true),
        @Index(name = "idx_emp_email",         columnList = "email",         unique = true),
        @Index(name = "idx_emp_department",    columnList = "department_id"),
        @Index(name = "idx_emp_status",        columnList = "employment_status"),
        @Index(name = "idx_emp_manager",       columnList = "manager_id")
    }
)
/**
 * @SQLDelete: When Hibernate executes a DELETE on this entity,
 * it runs this SQL instead — a soft delete.
 */
@SQLDelete(sql = "UPDATE employees SET is_deleted = true WHERE id = ?")
/**
 * @Where: Appended to every SELECT query on this entity.
 * All JPQL/Criteria queries automatically exclude deleted employees.
 * This applies to all associations too (e.g., department.getEmployees()).
 */
@Where(clause = "is_deleted = false")
@Getter
@Setter
@NoArgsConstructor
@AllArgsConstructor
@Builder
public class Employee {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * System-generated unique employee code (e.g., EMP-000001).
     * Generated in the service layer before saving.
     * Not auto-generated by DB — we control the format.
     */
    @Column(name = "employee_code", nullable = false, unique = true, length = 20)
    private String employeeCode;

    @Column(name = "first_name", nullable = false, length = 50)
    private String firstName;

    @Column(name = "last_name", nullable = false, length = 50)
    private String lastName;

    /**
     * Work email — unique. Used for notifications and login if needed.
     */
    @Column(name = "email", nullable = false, unique = true, length = 150)
    private String email;

    @Column(name = "phone_number", length = 20)
    private String phoneNumber;

    @Column(name = "date_of_birth")
    private LocalDate dateOfBirth;

    /**
     * @Enumerated(STRING): Stores "MALE", "FEMALE" etc. as strings.
     * Never use EnumType.ORDINAL — reordering enum constants breaks existing data.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "gender", length = 20)
    private Gender gender;

    /**
     * Freeform address. Stored as TEXT to accommodate long addresses.
     */
    @Column(name = "address", columnDefinition = "TEXT")
    private String address;

    /**
     * Job title / designation (e.g., "Senior Software Engineer", "HR Analyst").
     */
    @Column(name = "designation", length = 100)
    private String designation;

    /**
     * Date the employee joined the organization. Used for anniversary
     * calculations, earned leave accrual, etc.
     */
    @Column(name = "joining_date", nullable = false)
    private LocalDate joiningDate;

    /**
     * Monthly/annual salary. BigDecimal is mandatory for financial data —
     * never use float or double for money (floating-point precision errors).
     * precision=10, scale=2 supports up to 99,999,999.99
     */
    @Column(name = "salary", precision = 15, scale = 2)
    private BigDecimal salary;

    @Enumerated(EnumType.STRING)
    @Column(name = "employment_status", nullable = false, length = 20)
    @Builder.Default
    private EmploymentStatus employmentStatus = EmploymentStatus.ACTIVE;

    /**
     * The department this employee belongs to.
     *
     * @ManyToOne: Many employees belong to one department.
     * This side owns the foreign key (department_id column on employees table).
     * fetch = LAZY: load department data only when accessed.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "department_id")
    private Department department;

    /**
     * Self-referential Many-to-One for the manager hierarchy.
     * An employee's manager is also an Employee in the same table.
     * manager_id is a nullable FK back to employees.id.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "manager_id")
    private Employee manager;

    /**
     * Direct reports — employees managed by this employee.
     * mappedBy = "manager" means this is the inverse side.
     * FetchType.LAZY: load only when needed.
     */
    @OneToMany(mappedBy = "manager", fetch = FetchType.LAZY)
    @Builder.Default
    private List<Employee> directReports = new ArrayList<>();

    /**
     * One-to-One with User.
     * @JoinColumn: employees table holds the user_id FK.
     * cascade = PERSIST, MERGE: when saving/updating Employee, sync User changes.
     * NOT CascadeType.REMOVE — deleting an employee should not delete the User account
     * (the account may need to be disabled separately).
     */
    @OneToOne(fetch = FetchType.LAZY, cascade = {CascadeType.PERSIST, CascadeType.MERGE})
    @JoinColumn(name = "user_id", unique = true)
    private User user;

    /**
     * Bidirectional One-to-Many relationships.
     * FetchType.LAZY — never eagerly load collections.
     */
    @OneToMany(mappedBy = "employee", cascade = CascadeType.ALL,
               orphanRemoval = true, fetch = FetchType.LAZY)
    @Builder.Default
    private List<LeaveRequest> leaveRequests = new ArrayList<>();

    @OneToMany(mappedBy = "employee", cascade = CascadeType.ALL,
               orphanRemoval = true, fetch = FetchType.LAZY)
    @Builder.Default
    private List<LeaveBalance> leaveBalances = new ArrayList<>();

    @OneToMany(mappedBy = "employee", cascade = CascadeType.ALL,
               orphanRemoval = true, fetch = FetchType.LAZY)
    @Builder.Default
    private List<Attendance> attendanceRecords = new ArrayList<>();

    /**
     * Soft-delete flag. When true, @Where clause excludes this record
     * from all queries. @SQLDelete updates this flag instead of deleting.
     */
    @Column(name = "is_deleted", nullable = false)
    @Builder.Default
    private boolean deleted = false;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at")
    private LocalDateTime updatedAt;

    // ==================== Derived Helpers ====================

    /**
     * Convenience method: returns the employee's full name.
     * Not persisted — computed from stored fields.
     * @Transient annotation is not needed on methods; only on fields.
     */
    public String getFullName() {
        return firstName + " " + lastName;
    }
}

